function cfg = pidfra_params()
% PIDFRA_PARAMS Devuelve la configuracion completa del sistema PIDFRA_trainer.
%
% Replica exactamente las macros de firmware en include/app_config.h y define
% el modelo fisico continuo del motorreductor DC + puente H L298N + encoder
% incremental optico de 900 PPR en cuadratura x4 (3600 cuentas/vuelta).
%
% Uso:
%   cfg = pidfra_params();

  cfg = struct();

  % --- Parametros de muestreo, PWM y encoder (include/app_config.h) ---
  cfg.encoder_cycles_per_ch    = 900;
  cfg.quadrature_factor        = 4;
  cfg.counts_per_rev           = cfg.encoder_cycles_per_ch * cfg.quadrature_factor; % 3600
  cfg.deg_per_count            = 360.0 / cfg.counts_per_rev;                        % 0.1 deg

  cfg.control_period_ms        = 10;
  cfg.Ts                       = cfg.control_period_ms / 1000.0;                    % 0.01 s (100 Hz)
  cfg.fs_hz                    = 1.0 / cfg.Ts;

  cfg.pwm_freq_hz              = 20000;
  cfg.pwm_max_duty             = 255;

  % --- No linealidades compensadas y tolerancias de firmware ---
  cfg.default_min_move_duty    = 185;
  cfg.stall_min_duty           = 185;
  cfg.position_tolerance_counts = 8;     % +/- 0.8 grados

  % --- Supervisores de seguridad de la FSM ---
  cfg.encoder_startup_grace_ms = 300;
  cfg.encoder_stall_timeout_ms = 500;
  cfg.safety_max_search_revs   = 1.5;    % 5400 cuentas sin establecer SP
  cfg.safety_settle_ticks      = 5;      % 50 ms consecutivos dentro de banda
  cfg.safety_speed_ema_alpha   = 0.20;
  cfg.safety_speed_tol_ratio   = 0.15;

  % --- Modo demostracion CLOCK (segundero: 60 divisiones, 6 deg/s) ---
  cfg.clock_divisions_per_rev  = 60;
  cfg.clock_step_period_ms     = 1000;

  % --- Ganancias PID por defecto (include/app_config.h) ---
  cfg.speed_pid = struct( ...
    'kp', 0.1200, ...
    'ki', 0.1000, ...
    'kd', 0.0020, ...
    'out_min', 0.0, ...
    'out_max', double(cfg.pwm_max_duty) ...
  );

  cfg.pos_pid = struct( ...
    'kp', 0.4000, ...
    'ki', 0.2000, ...
    'kd', 0.0150, ...
    'out_min', -double(cfg.pwm_max_duty), ...
    'out_max',  double(cfg.pwm_max_duty) ...
  );

  cfg.clock_pid = struct( ...
    'kp', 1.5000, ...
    'ki', 1.0000, ...
    'kd', 0.0150, ...
    'out_min', -double(cfg.pwm_max_duty), ...
    'out_max',  double(cfg.pwm_max_duty) ...
  );

  % --- Potenciometros ADC1 y filtro digital EMA-IIR (lib/pot_adc) ---
  cfg.pot = struct( ...
    'period_ms',       50, ...
    'Ts',              0.050, ...
    'adc_raw_min',     0.0, ...
    'adc_raw_max',     4095.0, ...
    'v_min',           0.0, ...
    'v_max',           3.3, ...
    'multisample',     8, ...
    'ema_alpha',       0.25, ...
    'deadband_norm',   0.01, ...
    'zero_snap_norm',  0.015, ...
    'noise_std_lsb',   22.0, ...
    'speed_kp_range',  [0.00, 1.00], ...
    'speed_ki_range',  [0.00, 0.50], ...
    'speed_kd_range',  [0.000, 0.050], ...
    'speed_sp_range',  [0.0, 10.0], ...
    'pos_kp_range',    [0.00, 5.00], ...
    'pos_ki_range',    [0.00, 5.00], ...
    'pos_kd_range',    [0.000, 0.500], ...
    'pos_sp_range',    [0.0, 360.0], ...
    'clock_kp_range',  [0.00, 2.50], ...
    'clock_ki_range',  [0.00, 1.00], ...
    'clock_kd_range',  [0.000, 0.500], ...
    'open_sp_range',   [0.0, 255.0] ...
  );

  % --- Planta electromecanica continua (Motor DC + L298N + Reductora) ---
  % Sub-integracion continua con dt_phys << Ts para capturar ZOH, friccion
  % estatica/cinematica (stick-slip) y flancos discretos del encoder.
  cfg.plant = struct( ...
    'dt_phys',            0.0005, ...  % 0.5 ms (20 sub-pasos por periodo Ts=10ms)
    'tau_m',              0.090,  ...  % Constante de tiempo mecanica [s] (90 ms)
    'u_static',           178.0,  ...  % Umbral de despegue estatico [duty 0..255]
    'u_coulomb',          168.0,  ...  % Friccion seca cinetica de Coulomb [duty]
    'k_rpm_per_duty',     0.75,   ...  % Ganancia estacionaria efectiva [RPM/duty]
    'omega_stick_rpm',    0.12,   ...  % Umbral de captura stick alrededor de 0 RPM
    'load_duty_equiv',    0.0,    ...  % Perturbacion de par de carga externo [duty]
    'rotor_locked',       false,  ...  % Falla mecanica de eje bloqueado
    'encoder_open',       false   ...  % Falla electrica de fases A/B desconectadas
  );

  % Ganancias lineales equivalentes post-precompensacion de zona muerta:
  %   1 RPM = 6 deg/s = 60 cuentas/s (para N_c = 3600 cuentas/vuelta)
  cfg.plant.Km_rpm    = cfg.plant.k_rpm_per_duty;
  cfg.plant.Km_deg    = cfg.plant.k_rpm_per_duty * 6.0;
  cfg.plant.Km_counts = cfg.plant.k_rpm_per_duty * (cfg.counts_per_rev / 60.0);

  % --- Opciones de ley de control en simulacion ---
  % 'firmware_floor': replica motor_control.c linea 639 en SPEED: max(duty, min_duty)
  % 'additive_ff':    precompensacion aditiva manual_teoria §7.2: duty + min_duty
  cfg.speed_deadzone_mode = 'firmware_floor';
  cfg.enable_antiwindup   = true;
  cfg.enable_safety       = true;
end
